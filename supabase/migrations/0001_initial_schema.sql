-- Enable pgcrypto for crypt() / gen_salt() used by the seed file.
CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- ---------------------------------------------------------------------------
-- households
-- One row per protected household. safe_word_hash stores a bcrypt hash of
-- the family's safe word (never the plaintext).
-- ---------------------------------------------------------------------------
CREATE TABLE households (
  id                    uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  family_name           text        NOT NULL,
  senior_phone          text        NOT NULL,
  safe_word_hash        text        NOT NULL,
  time_waster_enabled   boolean     NOT NULL DEFAULT true,
  created_at            timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- contacts
-- Trusted phone numbers that bypass the AI screen and ring straight through.
-- ---------------------------------------------------------------------------
CREATE TABLE contacts (
  id            uuid  PRIMARY KEY DEFAULT gen_random_uuid(),
  household_id  uuid  NOT NULL REFERENCES households(id) ON DELETE CASCADE,
  name          text  NOT NULL,
  phone         text  NOT NULL,
  relationship  text  NOT NULL
);

CREATE INDEX contacts_household_id_idx ON contacts(household_id);
CREATE INDEX contacts_phone_idx        ON contacts(phone);

-- ---------------------------------------------------------------------------
-- family_members
-- People who receive alerts and / or accept callback transfers.
-- ---------------------------------------------------------------------------
CREATE TABLE family_members (
  id                  uuid    PRIMARY KEY DEFAULT gen_random_uuid(),
  household_id        uuid    NOT NULL REFERENCES households(id) ON DELETE CASCADE,
  name                text    NOT NULL,
  phone               text    NOT NULL,
  gets_alerts         boolean NOT NULL DEFAULT true,
  is_callback_target  boolean NOT NULL DEFAULT false
);

CREATE INDEX family_members_household_id_idx ON family_members(household_id);

-- ---------------------------------------------------------------------------
-- calls
-- One row per Twilio call leg handled by Ghostline.
-- state machine values: initiated | screening | verified | transferring |
--                       scam_blocked | time_wasted | completed | failed
-- risk_level values: low | medium | high | critical
-- outcome values: transferred | blocked | dropped | time_wasted | unknown
-- ---------------------------------------------------------------------------
CREATE TABLE calls (
  id                uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  household_id      uuid        NOT NULL REFERENCES households(id) ON DELETE CASCADE,
  call_sid          text        NOT NULL UNIQUE,
  from_number       text        NOT NULL,
  claimed_identity  text,
  state             text        NOT NULL DEFAULT 'initiated',
  risk_score        integer     CHECK (risk_score BETWEEN 0 AND 100),
  risk_level        text,
  outcome           text,
  started_at        timestamptz NOT NULL DEFAULT now(),
  ended_at          timestamptz,
  summary           text
);

CREATE INDEX calls_household_id_idx ON calls(household_id);
CREATE INDEX calls_call_sid_idx     ON calls(call_sid);
CREATE INDEX calls_started_at_idx   ON calls(started_at DESC);

-- ---------------------------------------------------------------------------
-- call_events
-- Append-only audit log for every meaningful event inside a call.
-- type values: transcript | red_flag | safe_word_attempt | callback_started |
--              callback_result | state_change | alert_sent
-- payload structure is type-specific (see lib/db.ts for per-type schemas).
-- ---------------------------------------------------------------------------
CREATE TABLE call_events (
  id          uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  call_id     uuid        NOT NULL REFERENCES calls(id) ON DELETE CASCADE,
  type        text        NOT NULL,
  payload     jsonb       NOT NULL DEFAULT '{}',
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX call_events_call_id_idx    ON call_events(call_id);
CREATE INDEX call_events_type_idx       ON call_events(call_id, type);
CREATE INDEX call_events_created_at_idx ON call_events(created_at DESC);

-- ---------------------------------------------------------------------------
-- fraud_reports
-- Full structured report generated by Gemini at end of a suspicious call.
-- ---------------------------------------------------------------------------
CREATE TABLE fraud_reports (
  id          uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  call_id     uuid        NOT NULL REFERENCES calls(id) ON DELETE CASCADE,
  report      jsonb       NOT NULL DEFAULT '{}',
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX fraud_reports_call_id_idx ON fraud_reports(call_id);

-- =============================================================================
-- Supabase Realtime
-- Enable row-level broadcast for the two tables the dashboard subscribes to.
-- =============================================================================

-- calls: dashboard shows live call state and risk score.
ALTER TABLE calls    REPLICA IDENTITY FULL;
ALTER TABLE call_events REPLICA IDENTITY FULL;

ALTER PUBLICATION supabase_realtime ADD TABLE calls;
ALTER PUBLICATION supabase_realtime ADD TABLE call_events;
